def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def category(path: Path) -> str:
    low = str(path).lower()
    if "master_project_handoff" in low:
        return "handoff"
    if "phase3b" in low or "phase3b_independent" in low:
        return "phase3b independent replication"
    if "phase3_geometry" in low:
        return "phase3a geometry pilot"
    if "phase2_specialist" in low:
        return "phase2 specialist decoder"
    if "noise_composition_phase" in low:
        return "phase1 noise composition"
    if "q-shift_v0.1_starter" in low.lower():
        return "starter project / personal notes"
    return "early exploratory outputs"


def status(path: Path) -> str:
    name = path.name.lower()
    if name.endswith(".npz"):
        return "raw data artifact; inspected by inventory/manifest notes, not replayed in this handoff"
    if name.endswith(".py"):
        return "source code; read/audited, not run in this handoff"
    if name.endswith(".json"):
        return "structured result/config/manifest; inspected as indicated in master report"
    if name.endswith(".png"):
        return "figure artifact; visual review limited to figures noted in phase reports"
    if name.endswith(".pkl") or name.endswith(".pickle"):
        return "saved pickle; deliberately not deserialized"
    if name.endswith(".docx"):
        return "text extracted; visual rendering unavailable (LibreOffice missing)"
    if name.endswith(".csv"):
        return "tabular data; inspected where described in master report"
    return "documentation/configuration/artifact; see master report for review scope"


